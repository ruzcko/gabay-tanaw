import {createObserverView,createSnapshotLoader} from './index.js';
import {createOverview} from './overview.js';
import {fixture} from './fixture.js';
import {withOverviewFixture} from './overview-fixture.js';
const output=document.querySelector('#results'),container=document.querySelector('#view'),lines=[];
const assert=(v,message)=>{if(!v)throw new Error(message);lines.push(`PASS ${message}`);output.textContent=lines.join('\n');};
const frame=()=>new Promise(resolve=>requestAnimationFrame(resolve));
let view,probe,loader;
try{
  let selection;
  view=createObserverView({container,onSiteSelect:value=>selection=value});
  let computationCalls=0;
  loader=createSnapshotLoader({observer:view,computationProvider:{async observe({site,instantUtc}){computationCalls++;return withOverviewFixture(fixture({site,instantUtc}));}}});
  let s=withOverviewFixture(fixture());await loader.load(s.site,s.instantUtc);view.lookToward('earth');await frame();const initial=view.getDiagnostics();
  view.setMode('overview');await frame();const first=view.getDiagnostics();
  assert(first.siteId===initial.siteId&&first.instantUtc===initial.instantUtc,'switch preserves shared site and time');
  assert(computationCalls===1,'both presentations reuse one computation result');
  assert(first.observerRenderCount===initial.observerRenderCount&&first.overviewRenderCount===1,'only active overview renders');
  assert(first.overview.siteMarkerVisible,'near-side marker visible');
  assert(container.querySelector('.observer-message').textContent.includes('not to scale'),'schematic scale visibly labelled');
  const back=fixture();back.site.longitudeEastDeg=180;back.site.id='far side';back.instantUtc='2026-11-14T01:00:00Z';s=withOverviewFixture(back);view.setSnapshot(s);await frame();
  assert(!view.getDiagnostics().overview.siteMarkerVisible,'far-side marker hidden');
  assert(container.querySelector('.overview-site-label').hidden,'far-side site label hidden');
  assert(container.querySelector('.overview-site-marker').hidden,'far-side site highlight hidden');
  view.setMode('observer');await frame();const returned=view.getDiagnostics();
  assert(returned.siteId==='far side'&&returned.instantUtc===s.instantUtc,'observer receives latest shared overview snapshot');
  assert(returned.overviewRenderCount===2,'inactive overview stops rendering');
  assert(!container.querySelectorAll('.observer-body')[1].textContent.includes('offscreen'),'observer camera orientation retained');
  view.setMode('overview',{focusSite:true});await frame();
  const focused=view.getDiagnostics();
  assert(focused.overview.siteMarkerVisible,'opening overview at current far-side site brings its marker into view');
  assert(!container.querySelector('.overview-site-marker').hidden&&container.querySelector('.overview-site-label').textContent.includes('Current site · far side'),'current site has a visible highlight and explicit label');
  assert(focused.siteId==='far side'&&focused.instantUtc===s.instantUtc&&computationCalls===1,'focusing current site preserves selection and time without recomputing');
  const opposite=withOverviewFixture(fixture());view.setSnapshot(opposite);await frame();
  assert(!view.getDiagnostics().overview.siteMarkerVisible,'new opposite-side selection starts outside overview camera');
  view.setMode('overview',{focusSite:true});await frame();
  assert(view.getDiagnostics().overview.siteMarkerVisible,'focusing a new site while already in overview reveals its marker');
  assert(view.getDiagnostics().siteId===opposite.site.id&&view.getDiagnostics().instantUtc===opposite.instantUtc&&computationCalls===1,'same-mode focus preserves scientific selection without recomputing');
  view.setSnapshot(fixture());await frame();
  assert(container.querySelector('.observer-message').textContent.includes('Waiting for Moon-frame'),'missing inputs show explicit waiting state');
  assert(!view.getDiagnostics().overview.siteMarkerVisible,'missing inputs do not retain stale marker');
  view.setSnapshot(withOverviewFixture(fixture()));await frame();
  probe=createOverview(container);probe.resize(container.clientWidth,container.clientHeight);probe.update(withOverviewFixture(fixture()),null);
  const halfFov=probe.camera.fov*Math.PI/360;
  const diameterFraction=1/(Math.tan(halfFov)*Math.sqrt(probe.diagnostics().distance**2-1));
  assert(diameterFraction>.5&&diameterFraction<.8,'default Moon fills more than half the viewport height');
  probe.resize(320,600);probe.update(withOverviewFixture(fixture()),null);
  const widthFraction=1/(Math.tan(probe.camera.fov*Math.PI/360)*probe.camera.aspect*Math.sqrt(probe.diagnostics().distance**2-1));
  assert(widthFraction>.5&&widthFraction<.8,'portrait framing keeps the enlarged Moon inside the viewport');
  probe.resize(container.clientWidth,container.clientHeight);
  const rect=container.getBoundingClientRect(),hit=probe.select(rect.left+rect.width/2,rect.top+rect.height/2);
  assert(Math.abs(hit.latitudeDeg-fixture().site.latitudeDeg)<.01&&Math.abs(hit.longitudeEastDeg-fixture().site.longitudeEastDeg)<.01,'Moon-center picking returns the focused site coordinates');
  probe.zoom(-1000);assert(probe.diagnostics().distance===2.5,'zoom has near bound');probe.zoom(1000);assert(probe.diagnostics().distance===18,'zoom has far bound');
  probe.orbit(0,1000);assert(Math.abs(Math.hypot(...probe.diagnostics().orientation)-1)<1e-10,'free orbit stays normalized through poles');probe.dispose();probe=null;
  assert(view.getDiagnostics().siteId===initial.siteId,'ray picking does not mutate shared selection');
  view.dispose();assert(container.children.length===0,'overview resources and labels removed on disposal');output.textContent=lines.join('\n')+'\nAll Stage 3 browser checks passed.';
}catch(error){output.textContent=lines.join('\n')+`\nFAIL ${error.stack}`;}
finally{loader?.dispose();probe?.dispose();view?.dispose();}
